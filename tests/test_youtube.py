# A stand-in with yt-dlp.exe's process shape: the venv python.exe is a launcher (like the PyInstaller
# bootloader) whose real interpreter starts a grandchild (like node) that inherits stdout/stderr.
_HANG_WITH_GRANDCHILD = (
    "import os, subprocess, sys, time\n"
    "g = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(600)'])\n"
    "open(sys.argv[1], 'w', encoding='utf-8').write(f'{os.getpid()} {g.pid}')\n"
    "print('[download] stalled', file=sys.stderr, flush=True)\n"
    "time.sleep(600)\n"
)


@pytest.mark.skipif(not paths.CORE_PYTHON.is_file(), reason="core venv python needed as a launcher stand-in")
def test_run_ytdlp_timeout_kills_the_whole_tree(tmp_path: Path) -> None:
    """Regression: subprocess.run(timeout=) killed only the launcher and then waited for the orphan."""
    pid_file = tmp_path / "pids.txt"
    t0 = time.monotonic()
    with pytest.raises(YoutubeError, match="초 안에 끝나지 않아 중단했습니다") as ei:
        youtube._run_ytdlp([str(paths.CORE_PYTHON), "-c", _HANG_WITH_GRANDCHILD, str(pid_file)], 3)
    elapsed = time.monotonic() - t0
    assert elapsed < 3 + 8, f"returned after {elapsed:.1f} s"
    assert "[download] stalled" in ei.value.stderr_tail
    for pid in (int(p) for p in pid_file.read_text(encoding="utf-8").split()):
        deadline = time.monotonic() + 5
        while winjob.pid_alive(pid):
            assert time.monotonic() < deadline, f"pid {pid} survived the timeout"
            time.sleep(0.05)


def _ytdlp_pids() -> set[int]:
    out = subprocess.run(["tasklist", "/FI", "IMAGENAME eq yt-dlp.exe", "/FO", "CSV", "/NH"],
                         capture_output=True, text=True, encoding="utf-8", errors="replace").stdout
    return {int(row.split('","')[1]) for row in out.splitlines() if row.startswith('"yt-dlp')}


class _LocalServer:
    """127.0.0.1 only, so the real-exe tests below never touch the internet."""

    def __init__(self, handler: Any) -> None:
        self.sock = socket.socket()
        self.sock.bind(("127.0.0.1", 0))
        self.sock.listen(8)
        self.port = self.sock.getsockname()[1]
        self.held: list[socket.socket] = []
        threading.Thread(target=self._serve, args=(handler,), daemon=True).start()

    def _serve(self, handler: Any) -> None:
        while True:
            try:
                conn, _ = self.sock.accept()
            except OSError:
                return
            self.held.append(conn)
            handler(conn)

    def close(self) -> None:
        self.sock.close()
        for c in self.held:
            c.close()


@pytest.mark.slow
@pytest.mark.skipif(not paths.YTDLP_EXE.is_file(), reason="tools/yt-dlp.exe not installed")
def test_real_ytdlp_on_a_hanging_server_is_stopped_at_the_timeout(tmp_path: Path) -> None:
    server = _LocalServer(lambda conn: None)  # accepts, never answers
    before = _ytdlp_pids()
    try:
        cmd = [str(paths.YTDLP_EXE), "--ignore-config", "--encoding", "utf-8", "--socket-timeout", "60",
               "--no-progress", "-o", str(tmp_path / "%(id)s.%(ext)s"), f"http://127.0.0.1:{server.port}/a.mp3"]
        t0 = time.monotonic()
        with pytest.raises(YoutubeError, match="중단했습니다"):
            youtube._run_ytdlp(cmd, 6)
        elapsed = time.monotonic() - t0
    finally:
        server.close()
    assert elapsed < 6 + 10, f"returned after {elapsed:.1f} s (yt-dlp's own socket timeout is 60 s)"
    assert _ytdlp_pids() <= before, "a yt-dlp.exe process outlived the timeout"


