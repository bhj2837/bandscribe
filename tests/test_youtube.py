def test_build_command_follows_spec_and_never_uses_cookies(tmp_path: Path) -> None:
    cfg = Config()
    cmd = youtube.build_command(f"https://youtu.be/{VID}", tmp_path / "dl", cfg)
    assert cmd[0] == str(paths.YTDLP_EXE)
    assert cmd[cmd.index("--config-locations") + 1] == str(paths.YTDLP_CONF)
