def test_ingest_url_end_to_end_with_fake(ytenv: Path, webm: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    fake = FakeYtdlp(webm)
    monkeypatch.setattr(youtube, "_run_ytdlp", fake)
    store = JobStore(ytenv / "jobs")
    r = ingest(f"https://music.youtube.com/watch?v={VID}&si=TRACKING", store=store, cfg=Config())
    assert r.cache_hit is False and r.song_key == f"yt-{VID}"
    meta = r.meta
    assert meta["source"]["kind"] == "youtube"
    assert meta["source"]["ref"] == f"https://www.youtube.com/watch?v={VID}"  # tracking parameter dropped
    assert meta["youtube"]["format_id"] == "251" and meta["youtube"]["abr"] == 135.4
    assert meta["youtube"]["title"] == "테스트 곡 (Official Audio)"
    assert meta["flags"]["drc"] is False
    inp = store.input_dir(r.song_key)
    assert meta["source"]["stored_as"] == "source.webm"
    assert (inp / "source.webm").read_bytes() == webm.read_bytes()  # original container, not re-encoded
    assert (inp / "mix_44k_f32.wav").is_file()
    assert store.index_get(f"yt:{VID}") == r.song_key
    assert store.index_get(f"file:{content_key(webm)}") == r.song_key
    assert (paths.DOWNLOADS / VID / f"{VID}.info.json").is_file()
    assert len(fake.calls) == 1

    # Second time: cache hit before any network access, whatever the URL shape.
    monkeypatch.setattr(youtube, "_run_ytdlp", _forbid_network)
    shutil.rmtree(paths.DOWNLOADS)  # not even the download cache is needed
    for url in (f"https://youtu.be/{VID}?si=other", f"https://www.youtube.com/watch?v={VID}"):
        again = ingest(url, store=store, cfg=Config())
        assert again.cache_hit is True and again.song_key == r.song_key and again.meta == meta

    # The downloaded file given as a local file maps to the same job.
    local = ingest(str(inp / "source.webm"), store=store, cfg=Config())
    assert local.cache_hit is True and local.song_key == r.song_key


