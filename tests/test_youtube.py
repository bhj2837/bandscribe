@pytest.mark.network
@pytest.mark.slow
def test_network_cc_clip_end_to_end(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    if not paths.YTDLP_EXE.is_file():
        pytest.skip(f"{paths.YTDLP_EXE} not installed")
    monkeypatch.setattr(paths, "DOWNLOADS", tmp_path / "downloads")
    calls: list[list[str]] = []
    real = youtube._run_ytdlp

    def spy(cmd: list[str], timeout_s: float) -> subprocess.CompletedProcess[str]:
        calls.append(list(cmd))
        return real(cmd, timeout_s)

    monkeypatch.setattr(youtube, "_run_ytdlp", spy)
    store = JobStore(tmp_path / "jobs")
    r = ingest(NET_URL, store=store, cfg=Config())

    assert r.cache_hit is False and r.song_key == f"yt-{NET_VID}"
    yt = r.meta["youtube"]
    assert yt["id"] == NET_VID and yt["channel"] == "Blender"
    assert yt["format_id"] and "drc" not in yt["format_id"]
    assert isinstance(yt["abr"], (int, float)) and yt["abr"] > 0
    assert yt["acodec"] and yt["ext"]
    assert 40 < r.meta["duration_s"] < 70
    # no cookies: the only yt-dlp call disabled them explicitly, and our config file adds none
    assert len(calls) == 1
    assert "--no-cookies" in calls[0] and "--no-cookies-from-browser" in calls[0]
    assert not {"--cookies", "--cookies-from-browser"} & set(calls[0])
    assert "cookies" not in paths.YTDLP_CONF.read_text(encoding="utf-8").lower()
    # original container kept byte for byte
    stored = store.input_dir(r.song_key) / r.meta["source"]["stored_as"]
    downloaded = paths.DOWNLOADS / NET_VID / f"{NET_VID}.{yt['ext']}"
    assert stored.read_bytes() == downloaded.read_bytes()
    assert r.meta["loudness"]["output_true_peak_dbfs"] <= Config().ingest.true_peak_ceiling_dbfs

    monkeypatch.setattr(youtube, "_run_ytdlp", _forbid_network)
    again = ingest(f"https://youtu.be/{NET_VID}?si=x", store=store, cfg=Config())
    assert again.cache_hit is True and again.song_key == r.song_key
