class FakeYtdlp:
    """Stands in for youtube._run_ytdlp: records commands and writes <id>.<ext> + <id>.info.json."""

    def __init__(self, audio: Path | None, info: dict[str, Any] | None = None, rc: int = 0, stderr: str = "") -> None:
        self.audio, self.info, self.rc, self.stderr = audio, info or _info(), rc, stderr
        self.calls: list[list[str]] = []

    def __call__(self, cmd: list[str], timeout_s: float) -> subprocess.CompletedProcess[str]:
        self.calls.append(list(cmd))
        if self.rc == 0 and self.audio is not None:
            out_dir = Path(cmd[cmd.index("-o") + 1]).parent
            vid, ext = self.info["id"], self.info["ext"]
            shutil.copyfile(self.audio, out_dir / f"{vid}.{ext}")
            atomic.write_json(out_dir / f"{vid}.info.json", self.info)
        return subprocess.CompletedProcess(cmd, self.rc, stdout="", stderr=self.stderr)


def _forbid_network(cmd: list[str], timeout_s: float) -> subprocess.CompletedProcess[str]:
    raise AssertionError(f"yt-dlp must not run here: {cmd}")


