def test_pace_spans_processes_via_the_stamp_file(ytenv: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """A second `bandscribe ingest <url>` is a new process: the wait must come from disk, not memory."""
    monkeypatch.setattr(youtube, "MIN_INTERVAL_S", 5.0)
    monkeypatch.setattr(youtube, "_last_download_end", 0.0)  # fresh process
    slept: list[float] = []
    monkeypatch.setattr(youtube.time, "sleep", slept.append)
    stamp = paths.DOWNLOADS / youtube.PACE_FILE
    atomic.write_text(stamp, f"{time.time() - 1.0:.3f}\n")
    youtube._pace()
    assert len(slept) == 1 and 3.5 < slept[0] <= 5.0
    # long ago, garbage, or a clock that went backwards: never more than MIN_INTERVAL_S, never an error
    for text in (f"{time.time() - 60:.3f}", "garbage", f"{time.time() + 3600:.3f}"):
        slept.clear()
        atomic.write_text(stamp, text)
        youtube._pace()
        assert all(0 < s <= 5.0 for s in slept)


